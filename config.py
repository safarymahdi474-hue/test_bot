def get_rank(points: int) -> str:
    """مقام کاربر بر اساس امتیاز فعلیش."""
    current = RANKS[0][1]
    for threshold, name in RANKS:
        if points >= threshold:
            current = name
        else:
            break
    return current


def get_next_rank(points: int):
    """(نام مقام بعدی, امتیاز موردنیاز باقی‌مانده) یا None اگه بالاترین مقامه."""
    for threshold, name in RANKS:
        if points < threshold:
            return name, threshold - points
    return None


